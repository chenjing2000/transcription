"""Single public transcribe entry point.

Actual inference and output publishing are later roadmap stages.
"""
from __future__ import annotations

from pathlib import Path
from .errors import TranscriptionError
from .registry import get_engine
from .result import TranscriptionResult

SUPPORTED_SUFFIXES = {".mp4", ".mkv", ".mp3", ".wav"}
DEVICES = {"cpu", "gpu", "auto"}


def transcribe(
    file_path: str | Path,
    engine: str,
    *,
    device: str = "auto",
    audio_track: int = 0,
) -> TranscriptionResult:
    """Validate the request; engine execution is NOT IMPLEMENTED yet.

    Expected task errors return a failed result, including missing files and
    engines not found. No files are generated by this implementation.
    """
    source = Path(file_path)
    result = TranscriptionResult(
        status="failed", info="", engine=engine, source_path=source,
        device=device,
    )
    try:
        if not isinstance(device, str) or device not in DEVICES:
            raise TranscriptionError("INVALID_DEVICE", "device must be gpu, cpu or auto")
        if not isinstance(audio_track, int) or isinstance(audio_track, bool) or audio_track < 0:
            raise TranscriptionError("INVALID_AUDIO_TRACK", "audio_track must be a nonnegative integer")
        get_engine(engine)
        if source.suffix.lower() not in SUPPORTED_SUFFIXES:
            raise TranscriptionError("UNSUPPORTED_FORMAT", "Supported inputs: mp4, mkv, mp3, wav")
        if not source.is_file():
            raise TranscriptionError("INVALID_INPUT", f"Input file does not exist: {source}")
        raise TranscriptionError(
            "NOT_IMPLEMENTED",
            "Engine recognition, FFmpeg extraction and output writing are planned for Phases 3–6",
        )
    except TranscriptionError as exc:
        result.error_code = exc.code
        result.info = str(exc)
        return result
